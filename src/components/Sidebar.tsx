export default function Sidebar() {
  const pathname = usePathname();
  const { userProfile, session } = useAuth();

  const displayName = userProfile?.full_name || session?.user?.user_metadata?.full_name || "Usuário";
  const displayEmail = userProfile?.email || session?.user?.email || "";
  const initials = displayName
    .split(" ")
    .map((w: string) => w[0])
    .slice(0, 2)
    .join("")
    .toUpperCase();

  return (
    <aside className="fixed left-0 top-0 h-screen w-64 bg-surface hidden md:flex flex-col z-50 border-r border-border">
      {/* Logo */}
      <div className="px-6 py-6 border-b border-border">
        <Link href="/dashboard" className="flex items-center gap-3">
          <Image
            src="/assets/logo.png"
            alt="KZ Servicos"
            width={890}
            height={494}
            className="h-9 w-auto object-contain"
          />
          <span className="text-dark font-heading font-black text-xl tracking-tight">
            Painel ADM
          </span>
        </Link>
      </div>

      {/* Navigation */}
      <nav className="flex-1 px-3 py-4 space-y-1 overflow-y-auto">
        {navItems.map((item) => {
          const isActive =
            pathname === item.href || pathname.startsWith(`${item.href}/`);
          return (
            <Link
              key={item.href}
              href={item.href}
              className={`flex items-center gap-3 px-3 py-2.5 rounded-lg text-sm transition-all duration-150 ${
                isActive
                  ? "bg-primary text-background font-semibold"
                  : "text-contrast hover:bg-surface-hover hover:text-dark"
              }`}
            >
              {item.icon}
              {item.label}
            </Link>
          );
        })}
      </nav>

      {/* User section */}
      <div className="px-4 py-4 border-t border-border">
        <div className="flex items-center gap-3">
          <div className="w-8 h-8 rounded-full bg-contrast flex items-center justify-center">
            <span className="text-background text-xs font-semibold">{initials}</span>
          </div>
          <div className="flex-1 min-w-0">
            <p className="text-dark text-sm font-medium truncate">{displayName}</p>
            <p className="text-contrast text-xs truncate">{displayEmail}</p>
          </div>
          <ThemeToggle className="text-contrast hover:text-dark" />
          <button
            onClick={async () => {
              await signOut();
              window.location.href = "/login";
            }}
            className="text-contrast hover:text-dark transition-colors cursor-pointer"
            title="Sair"
          >
            <svg width="18" height="18" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round">
              <path d="M9 21H5a2 2 0 0 1-2-2V5a2 2 0 0 1 2-2h4" />
              <polyline points="16 17 21 12 16 7" />
              <line x1="21" y1="12" x2="9" y2="12" />
            </svg>
          </button>
        </div>
      </div>
    </aside>
  );
}
